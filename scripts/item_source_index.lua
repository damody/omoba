-- Source item index (E155, E169): damody/history_nobu items as a provenance catalog.
--
--   tools\lua\lua.exe scripts\item_source_index.lua index  [--source <checkout>] [--out <file>]
--   tools\lua\lua.exe scripts\item_source_index.lua verify [--source <checkout>] [--catalog <file>]
--
-- The checkout must be at the pinned commit the heroes use (source-index). The catalog is
-- written to docs/plans/2026-10-24-omfue-month-mvp/source-index/source-item-catalog.lua.
local source_file = debug.getinfo(1, "S").source:sub(2)
package.path = assert(source_file:match("^(.*)[/\\]")) .. "/?.lua;" .. package.path
local b = require("_bootstrap")
local path = b.lib("path")
local catalog = require("item_source.catalog")
local serialize = require("hero_source.serialize")

local PINNED = "f966720b0956d002099d72aabec7ddc94b16d4bf"
local DEFAULT_SOURCE = path.join(b.root, "target", "source", "history_nobu")
local NAME = "history_nobu"
local DEFAULT_OUT = path.join(b.root, "docs", "plans", "2026-10-24-omfue-month-mvp", "source-index", "source-item-catalog.lua")

local command = arg[1]
local opts = {}
local i = 2
while i <= #arg do
  local key = arg[i]:match("^%-%-(.+)$")
  assert(key, "unexpected argument: " .. arg[i])
  opts[key] = arg[i + 1]
  i = i + 2
end
local source = path.absolute(opts.source or DEFAULT_SOURCE, b.root)
local commit = require("hero_source.catalog").checkout_commit(source)
assert(commit == PINNED, ("source checkout must be at %s, found %s"):format(PINNED, tostring(commit)))

if command == "index" then
  local result = catalog.build(source)
  result.source = { name = NAME, repository = "https://github.com/damody/history_nobu", commit = commit }
  local out = path.absolute(opts.out or DEFAULT_OUT, b.root)
  path.write(out, serialize.serialize(result,
    "-- Generated by tools\\lua\\lua.exe scripts\\item_source_index.lua index; do not edit.\n"), true, true)
  local listed, recipes = 0, 0
  for _, item in ipairs(result.items) do
    if item.listed then listed = listed + 1 end
    if item.recipe then recipes = recipes + 1 end
  end
  print(("items %d (in shops %d, with recipe %d), orphan recipes %d, parse diagnostics %d -> %s"):format(
    #result.items, listed, recipes, #result.orphan_recipes, result.diagnostics, out))
elseif command == "export" then
  -- The build-time view of the catalog (data only, read by templates/moba_items.lua through
  -- ctx.include): what an item must equal to cite a source row.
  local file = path.absolute(opts.catalog or DEFAULT_OUT, b.root)
  local loaded = assert(loadfile(file, "t", {}))()
  local compare = require("item_source_compare")
  local by_key = {}
  for _, item in ipairs(loaded.items) do by_key[item.key] = item end
  compare.index(loaded)
  local rows = {}
  for _, item in ipairs(loaded.items) do
    if item.listed then
      local stats = {}
      for _, p in ipairs(compare.passive_properties(item)) do
        local field = compare.SUPPORTED[p.property]
        if field and p.value ~= 0 and p.value ~= "0" then stats[field] = (stats[field] or 0) + tonumber(p.value) end
      end
      local recipe = item.recipe and item.recipe[1]
      local translated = compare.active(item)
      rows[#rows + 1] = {
        active = translated and translated.active or nil,
        cooldown = translated and translated.cooldown or nil,
        mana_cost = translated and translated.mana_cost ~= 0 and translated.mana_cost or nil,
        consumable = translated and translated.consumable or nil,
        shares_cooldown_with = translated and translated.shares_cooldown_with or nil,
        aura = (compare.aura(item) or {}).aura,
        unique_passive = compare.unique_passive(item),
        target = translated and translated.target or nil,
        key = "item_" .. item.key,
        source_ref = NAME .. "@" .. commit .. ":item_" .. item.key,
        name = item.name,
        description = item.description,
        cost = compare.total_cost(item, by_key),
        recipe = recipe and recipe.requirements[1] and {
          components = (function() local c = {} for _, k in ipairs(recipe.requirements[1]) do c[#c + 1] = NAME .. "@" .. commit .. ":item_" .. k end return c end)(),
          combine_cost = recipe.cost } or nil,
        stats = stats,
        modifiers = compare.modifiers(item),
        gaps = compare.gaps(item, by_key),
        shops = item.shops,
      }
    end
  end
  -- lua_data is a live input (E143): export into a workspace and land the file with
  -- land_to_live, never straight into scripts/lua_data.
  local out = path.absolute(assert(opts.out, "export needs --out <workspace>/scripts/lua_data/templates/source_items.lua"), b.root)
  -- A template module (ctx.include returns what the function returns).
  local data = serialize.serialize({ name = NAME, commit = commit, items = rows }):gsub("^return ", "")
  path.write(out, "-- Generated by tools\\lua\\lua.exe scripts\\item_source_index.lua export from source-item-catalog.lua; do not edit.\n"
    .. "-- Build-time source of truth for MOBA items (E155): templates/moba_items.lua cites rows by source_ref.\n"
    .. "return function(ctx)\n  return " .. data .. "end\n", true, true)
  print(("exported %d shop items -> %s"):format(#rows, out))
elseif command == "verify" then
  local file = path.absolute(opts.catalog or DEFAULT_OUT, b.root)
  local loaded = assert(loadfile(file, "t", {}))()
  local problems = catalog.verify(loaded, source)
  for _, p in ipairs(problems) do print("MISMATCH " .. p) end
  print(("verified %d items: %d mismatches"):format(#loaded.items, #problems))
  if #problems > 0 then os.exit(1) end
else
  io.stderr:write("usage: item_source_index.lua index|verify [--source <checkout>] [--out|--catalog <file>]\n")
  os.exit(2)
end
