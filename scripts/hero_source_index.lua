-- Hero source index (plan D1/D2; future `index` subcommand of the authoring tool).
--
--   tools\lua\lua.exe scripts\hero_source_index.lua index  --source <checkout> [--out <dir>]
--   tools\lua\lua.exe scripts\hero_source_index.lua verify --source <checkout> [--catalog <file>]
--   tools\lua\lua.exe scripts\hero_source_index.lua requirements [--requirements <file>] [--out <md>]  (D3 tables)
--   tools\lua\lua.exe scripts\hero_source_index.lua export --hero <id> --out <md> [--catalog <file>]  (raw source pack)
--   tools\lua\lua.exe scripts\hero_source_index.lua capabilities --out <md> [--requirements <file>]  (capability registry only)
--   tools\lua\lua.exe scripts\hero_source_index.lua coverage [--out <dir>] [--blind C15=pkg,B29=pkg]  (delivery kit coverage)
--
-- The source checkout is untrusted data: it is read as text only and must be
-- at the pinned commit. Nothing inside it is executed.
local script = debug.getinfo(1, "S").source:sub(2)
local dir = script:match("^(.*)[/\\]") or "."
package.path = dir .. "/?.lua;" .. package.path
local b = require("_bootstrap")
local path = b.lib("path")
local args = b.lib("args")
local hash = b.lib("hash")
local catalog_mod = require("hero_source.catalog")
local summary = require("hero_source.summary")
local serialize = require("hero_source.serialize")
local sha256 = require("hero_source.sha256")

local REPOSITORY = "https://github.com/damody/nobugg_official"
local COMMIT = "ca6ee8602473f6015a397cc121dac6baeb70b2e5"
local DEFAULT_OUT = path.join(b.root, "docs", "plans", "2026-10-24-omfue-month-mvp", "source-index")

local function usage()
  io.stderr:write("usage: hero_source_index.lua index|verify --source <checkout> [--out <dir>] [--catalog <file>] [--commit <sha>] | requirements [--catalog <file>] [--requirements <file>] [--out <md>]\n")
  os.exit(2)
end

local function load_catalog(file)
  local chunk = assert(load(path.read(file, true), "@" .. file, "t", {}))
  return chunk()
end

local opts = args.parse(arg)
local command = opts.positional[1]
if command == "requirements" then
  -- D3 tables: validate against the catalog and render the markdown view.
  local requirements = require("hero_source.requirements")
  local catalog_file = type(opts.catalog) == "string" and path.absolute(opts.catalog) or path.join(DEFAULT_OUT, "source-catalog.lua")
  local req_file = type(opts.requirements) == "string" and path.absolute(opts.requirements)
    or path.join(DEFAULT_OUT, "candidate-requirements.lua")
  local catalog = load_catalog(catalog_file)
  local req = load_catalog(req_file)
  local derived, problems = requirements.validate(req, catalog)
  for _, p in ipairs(problems) do io.stderr:write(p .. "\n") end
  if #problems > 0 then os.exit(1) end
  local out = type(opts.out) == "string" and path.absolute(opts.out) or path.join(path.parent(req_file), "d3-requirements.md")
  path.write(out, requirements.render(req, catalog, derived), true, true)
  for _, h in ipairs(req.heroes) do
    print(string.format("%s %-8s %s", h.source_hero_id, h.roster, derived.heroes[h.source_hero_id].status))
  end
  os.exit(0)
end
if command == "coverage" then
  -- Delivery kits and blind heroes, read from their packages.
  local coverage = require("hero_source.coverage")
  local out = type(opts.out) == "string" and path.absolute(opts.out) or DEFAULT_OUT
  local blind = {}
  if type(opts.blind) == "string" then for id, pkg in opts.blind:gmatch("(%w+)=([%w_]+)") do blind[id] = pkg end end
  local rows = coverage.collect(path.join(b.root, "docs", "character_pipeline", "packages"):gsub("\\", "/"),
    load_catalog(path.join(DEFAULT_OUT, "source-catalog.lua")), blind)
  path.write(path.join(out, "kit-coverage.lua"), serialize.serialize({ kits = rows },
    "-- Generated by scripts/hero_source_index.lua coverage; do not edit.\n"), true, true)
  path.write(path.join(out, "kit-coverage.md"), coverage.render(rows), true, true)
  for _, r in ipairs(rows) do print(string.format("%-3s %s %-16s %s", r.plan, r.source, r.package or "-", r.kit_status)) end
  os.exit(0)
end
if command == "capabilities" then
  if type(opts.out) ~= "string" then usage() end
  local req_file = type(opts.requirements) == "string" and path.absolute(opts.requirements)
    or path.join(DEFAULT_OUT, "candidate-requirements.lua")
  path.write(path.absolute(opts.out), require("hero_source.export").capabilities(load_catalog(req_file)), true, true)
  print("wrote capability registry")
  os.exit(0)
end
if command == "export" then
  -- Raw source pack (provenance, unit KV, tooltips, ability KV) for one hero.
  if type(opts.hero) ~= "string" or type(opts.out) ~= "string" then usage() end
  local catalog_file = type(opts.catalog) == "string" and path.absolute(opts.catalog) or path.join(DEFAULT_OUT, "source-catalog.lua")
  local text = require("hero_source.export").render(load_catalog(catalog_file), opts.hero)
  path.write(path.absolute(opts.out), text, true, true)
  print("exported " .. opts.hero .. " (" .. #text .. " bytes)")
  os.exit(0)
end
if command ~= "index" and command ~= "verify" then usage() end
if type(opts.source) ~= "string" then usage() end
local source = path.absolute(opts.source):gsub("\\", "/")
local commit = type(opts.commit) == "string" and opts.commit or COMMIT

if command == "index" then
  local out = type(opts.out) == "string" and path.absolute(opts.out) or DEFAULT_OUT
  local catalog = catalog_mod.build({ source = source, repository = REPOSITORY, commit = commit,
    repo_root = b.root:gsub("\\", "/") })
  -- Whole-file hashes are cross-checked against the lua-host implementation.
  for _, f in ipairs(catalog.files) do
    local host_hash = hash.sha256(source .. "/" .. f.path)
    assert(host_hash == f.sha256, "sha256 mismatch for " .. f.path)
  end
  local problems, checked = catalog_mod.verify(catalog, source)
  assert(#problems == 0, "self-verify failed:\n" .. table.concat(problems, "\n"))
  local header = "-- Generated by scripts/hero_source_index.lua index; do not edit.\n" ..
    "-- Source: " .. REPOSITORY .. " @ " .. commit .. "\n"
  local text = serialize.serialize(catalog, header)
  path.write(path.join(out, "source-catalog.lua"), text, true, true)
  path.write(path.join(out, "summary.md"), summary.render(catalog), true, true)
  print(string.format("indexed %d files, %d heroes, %d ability blocks; %d spans verified; catalog sha256 %s",
    #catalog.files, #catalog.heroes, #catalog.abilities, checked, sha256(text)))
else
  local file = type(opts.catalog) == "string" and path.absolute(opts.catalog) or path.join(DEFAULT_OUT, "source-catalog.lua")
  local catalog = load_catalog(file)
  assert(catalog.schema == catalog_mod.SCHEMA, "unexpected catalog schema " .. tostring(catalog.schema))
  local actual = catalog_mod.checkout_commit(source)
  assert(actual == catalog.source.commit, "source checkout is at " .. tostring(actual) .. ", catalog was built from " .. catalog.source.commit)
  local problems, checked = catalog_mod.verify(catalog, source)
  for _, p in ipairs(problems) do io.stderr:write(p .. "\n") end
  if #problems > 0 then os.exit(1) end
  print(string.format("verified %d spans and %d file hashes against %s", checked, #catalog.files, source))
end
