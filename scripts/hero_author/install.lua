-- Idempotent include hooks that append authored packages after every
-- hand-written template entry (append-only content IDs). Installed by
-- `hero_author.lua build`; never reorders existing declarations.
local M = {}

M.MARKER = "-- @hero_author:authored-include"

M.HOOKS = {
  ["templates/heroes.lua"] = {
    final_return = "return heroes",
    code = [[
  -- @hero_author:authored-include (scripts/hero_author.lua build): packages are
  -- appended after every hand-written hero; updates only replace slot entries.
  do
    local authored = ctx.include('templates/authored_heroes.lua')
    for _, hero in ipairs(authored.heroes or {}) do heroes[#heroes + 1] = hero end
    for _, hero in ipairs(heroes) do
      local update = (authored.hero_updates or {})[hero.id]
      if update then
        assert(update.rust_module == hero.rust_module, hero.id .. ': authored update rust_module mismatch')
        local list = {}
        for i, id in ipairs(hero.abilities or {}) do list[i] = id end
        for i = 1, 4 do if update.abilities_by_slot[i] then list[i] = update.abilities_by_slot[i] end end
        -- Replaced abilities stay registered (gen_hero_registry reads
        -- retained_abilities) so legacy content keeps its handlers and tests.
        local kept, in_list = {}, {}
        for _, id in ipairs(list) do in_list[id] = true end
        for _, id in ipairs(hero.retained_abilities or {}) do if not in_list[id] then kept[#kept + 1] = id; in_list[id] = true end end
        for _, id in ipairs(hero.abilities or {}) do if not in_list[id] then kept[#kept + 1] = id; in_list[id] = true end end
        hero.abilities = list
        hero.retained_abilities = kept
        -- Birth ranks follow the replaced slots; other slots keep the hero's own.
        local loadout = hero.moba_loadout or {}
        local base = loadout.ranks or { 1, 1, 1, 1 }
        local ranks = {}
        for i = 1, 4 do ranks[i] = (update.ranks_by_slot or {})[i] or base[i] end
        hero.moba_loadout = { ranks = ranks, skill_points = update.skill_points or loadout.skill_points or 0 }
      end
    end
  end
]],
  },
  ["templates/summons.lua"] = {
    -- summons.lua returns its list literally: splice the authored rows in as
    -- the constructor's last (multi-value) field, keeping append-only order.
    before_last = "\n  }\nend",
    code = [[
    -- @hero_author:authored-include (scripts/hero_author.lua build): authored summons appended last.
    (function()
      local out = {}
      local visuals = ctx.include('templates/moba_native_visuals.lua')
      for _, summon in ipairs(ctx.include('templates/authored_heroes.lua').summons or {}) do
        local row = {}
        for key, value in pairs(summon) do row[key] = value end
        local profile = row.native_visual_profile
        row.native_visual_profile = nil
        if profile then
          local base = assert(visuals[profile], 'unknown native visual profile ' .. tostring(profile))
          local visual = {}
          for key, value in pairs(base) do visual[key] = value end
          row.ue = { native_only = true, native_visual = visual }
        end
        out[#out + 1] = row
      end
      return table.unpack(out)
    end)(),
]],
  },
  ["templates/abilities.lua"] = {
    final_return = "return abilities",
    code = [[
  -- @hero_author:authored-include (scripts/hero_author.lua build): appended last.
  for _, ability in ipairs(ctx.include('templates/authored_heroes.lua').abilities or {}) do
    abilities[#abilities + 1] = ability
  end
]],
  },
}

local EMPTY = "-- GENERATED by scripts/hero_author.lua build; no packages built yet.\n" ..
  "return function(ctx) return { packages = {}, heroes = {}, hero_updates = {}, abilities = {} } end\n"
M.EMPTY_AUTHORED = EMPTY

-- Returns the new text, or nil when the hook is already present.
function M.patch(relative, text)
  local hook = assert(M.HOOKS[relative], "no hook for " .. relative)
  if text:find(M.MARKER, 1, true) then return nil end
  local crlf = text:find("\r\n", 1, true) ~= nil
  local norm = text:gsub("\r\n", "\n")
  if hook.before_last then
    local last, init = nil, 1
    while true do
      local s = norm:find(hook.before_last, init, true)
      if not s then break end
      last, init = s, s + 1
    end
    assert(last, relative .. ": cannot find '" .. hook.before_last:gsub("\n", "\\n") .. "'")
    local out = norm:sub(1, last) .. hook.code .. norm:sub(last + 1)
    if crlf then out = out:gsub("\n", "\r\n") end
    return out
  end
  -- Insert before the last `return <list>` of the builder.
  local last
  local init = 1
  while true do
    local s = norm:find("\n%s*" .. hook.final_return:gsub("%s", "%%s") .. "%s*\n", init)
    if not s then break end
    last = s
    init = s + 1
  end
  assert(last, relative .. ": cannot find final '" .. hook.final_return .. "'")
  local out = norm:sub(1, last) .. hook.code .. norm:sub(last + 1)
  if crlf then out = out:gsub("\n", "\r\n") end
  return out
end

return M
