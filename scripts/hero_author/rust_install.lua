-- Package-owned Rust handlers (README §4.3: a package carries its generated
-- Rust files). `build` installs them into scripts/base_content together with
-- the authored content, inside the same rollback, because the handlers name
-- template IDs (omoba_template_ids::ABILITY_*) that exist only once that
-- content is generated. Installing either half alone would break the build.
local lfs = require("lfs")
local M = {}

local function read(p)
  local f = io.open(p, "rb"); if not f then return nil end
  local t = f:read("a"); f:close(); return t
end

-- Appends `line` before the end of `text` unless `needle` is already present,
-- keeping the file's line ending style.
local function ensure_line(text, needle, line)
  if text:find(needle, 1, true) then return text end
  local nl = text:find("\r\n", 1, true) and "\r\n" or "\n"
  if text ~= "" and not text:find("\n$") then text = text .. nl end
  return text .. line:gsub("\n", nl) .. nl
end

-- Returns writes ({ [path] = text }), the set of exported ability ids and the
-- package Rust files, or nil when the package carries no Rust directory.
-- slice: set of ability ids being built, or nil for the whole kit. A file
-- that implements only abilities outside the slice is not installed, so a
-- handler for a not-yet-supported ability never has to compile.
function M.plan(root, package_dir, pkg, slice)
  local rust_dir = package_dir .. "/rust"
  if lfs.attributes(rust_dir, "mode") ~= "directory" then return nil end
  local module = assert(pkg.character.identity.rust_module, "package rust/ needs identity.rust_module")
  local files = {}
  for name in lfs.dir(rust_dir) do
    if name:match("^[%w_]+%.rs$") and name ~= "mod.rs" then files[#files + 1] = name end
  end
  table.sort(files)
  if slice then
    local wanted, excluded = {}, {}
    for _, ab in ipairs(pkg.abilities.abilities) do
      local module = (ab.implementation or {}).module
      if module then if slice[ab.id] then wanted[module] = true else excluded[module] = true end end
    end
    local kept = {}
    for _, name in ipairs(files) do
      local stem = name:sub(1, -4)
      if wanted[stem] or not excluded[stem] then kept[#kept + 1] = name end
    end
    files = kept
  end
  local heroes_dir = root .. "/scripts/base_content/src/heroes"
  local module_dir = heroes_dir .. "/" .. module
  local writes, exported = {}, {}
  local mod_path = module_dir .. "/mod.rs"
  local mod_text = read(mod_path) or ("//! " .. pkg.character.hero.display_name .. "（" .. module .. "）— generated by hero_author build.\n")
  for _, name in ipairs(files) do
    local stem = name:sub(1, -4)
    writes[module_dir .. "/" .. name] = assert(read(rust_dir .. "/" .. name))
    -- Test fixtures and the package's own parity soak exist only in tests.
    local test_only = stem:match("_test_support$") or stem == "parity_soak"
    local decl = test_only and ("#[cfg(test)]\npub(crate) mod " .. stem .. ";") or ("pub mod " .. stem .. ";")
    mod_text = ensure_line(mod_text, "mod " .. stem .. ";", decl)
  end
  for _, ab in ipairs(pkg.abilities.abilities) do
    local impl = ab.implementation or {}
    if impl.kind == "rust_handler" and impl.module and writes[module_dir .. "/" .. impl.module .. ".rs"]
      and (slice == nil or slice[ab.id]) then
      mod_text = ensure_line(mod_text, ab.id .. "_ffi;", "pub use " .. impl.module .. "::" .. ab.id .. "_ffi;")
      exported[ab.id] = true
    end
  end
  if writes[module_dir .. "/hero_unit.rs"] then
    mod_text = ensure_line(mod_text, "hero_unit::hero_unit_script;", "pub use hero_unit::hero_unit_script;")
  end
  writes[mod_path] = mod_text
  local heroes_mod = heroes_dir .. "/mod.rs"
  local heroes_text = read(heroes_mod) or ""
  local patched = ensure_line(heroes_text, "mod " .. module .. ";", "pub mod " .. module .. ";")
  if patched ~= heroes_text then writes[heroes_mod] = patched end
  local installed = {}
  for p in pairs(writes) do installed[#installed + 1] = p end
  table.sort(installed)
  return { writes = writes, exported = exported, files = installed }
end

return M
