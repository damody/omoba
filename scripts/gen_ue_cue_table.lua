-- UE presentation cue table (M6 work line C): the cue catalog that line A generates from the v3
-- documents and the original history_nobu sources (docs/character_pipeline/presentation/
-- cue-catalog.lua) as a compiled C++ table for OmRuntime's FOmCueCatalog. The game never reads
-- Lua; UE gets every cue's kind (to pick a generic placeholder effect) and the original asset
-- paths, both ways: cue -> original paths and original path -> cues. Editor overrides live in
-- UOmCueSettings, not here.
--
--   tools\lua\lua.exe scripts\gen_ue_cue_table.lua [--root DIR] [--out FILE] [--check]
--
-- --check compares instead of writing and fails when FILE is stale (scripts/tests/ue_cue_table_test.lua).
local source = debug.getinfo(1, "S").source:sub(2)
local scripts_dir = assert(source:match("^(.*)[/\\]"))
package.path = scripts_dir .. "/?.lua;" .. package.path
local b = require("_bootstrap")

local M = {}
M.CATALOG = "docs/character_pipeline/presentation/cue-catalog.lua"
M.OUT = "omfue/Plugins/OmRuntime/Source/OmRuntime/Private/OmCueCatalogData.inl"
-- EOmCueKind order (OmCueCatalog.h); index 0 is Unknown
M.KINDS = { "effect", "sound", "projectile", "area", "link", "aura", "summon", "channel", "impact", "gesture" }
M.ASSET_KINDS = { particle = "Particle", sound = "Sound" }

local KIND_INDEX = {}
for i, k in ipairs(M.KINDS) do KIND_INDEX[k] = i end
local function enum_name(kind) return kind:sub(1, 1):upper() .. kind:sub(2) end

local function sorted_keys(t)
  local list = {}
  for k in pairs(t) do list[#list + 1] = k end
  table.sort(list)
  return list
end

local function cxx_string(s)
  assert(not s:find('[%c"]'), "unexpected character in " .. s)
  -- a few original paths are written with backslashes; they stay as written
  return 'TEXT("' .. s:gsub("\\", "\\\\") .. '")'
end

-- catalog table -> C++ source text
function M.render(catalog)
  local ids = sorted_keys(catalog.cues)
  local cue_index = {}
  for i, id in ipairs(ids) do
    assert(id:match("^[%w_%.%-]+$"), "cue id " .. id)
    cue_index[id] = i - 1
  end
  local paths = sorted_keys(catalog.assets)
  local path_known = {}
  for _, p in ipairs(paths) do path_known[p] = true end

  local out = {
    "// GENERATED by scripts/gen_ue_cue_table.lua from " .. M.CATALOG .. " (" ..
      catalog.source.repository .. "@" .. catalog.source.commit .. "); do not edit.",
    "// Included once by OmCueCatalog.cpp.",
    "#define OM_CUE_CATALOG_SOURCE TEXT(\"" .. catalog.source.repository .. "@" .. catalog.source.commit .. "\")",
    "",
    "static const TCHAR* const GOmCueAssetPaths[] = {",
  }
  -- cue -> original paths, flattened in cue order
  local cue_rows, begin = {}, 0
  for _, id in ipairs(ids) do
    local cue = catalog.cues[id]
    local kind = assert(KIND_INDEX[cue.kind], "cue " .. id .. " kind " .. tostring(cue.kind))
    local mask = 0
    for _, k in ipairs(cue.kinds or { cue.kind }) do mask = mask | (1 << assert(KIND_INDEX[k], "cue " .. id .. " kinds " .. k)) end
    local assets = cue.assets or {}
    for _, a in ipairs(assets) do
      assert(path_known[a.path], "cue " .. id .. " asset " .. a.path .. " missing from assets")
      out[#out + 1] = "\t" .. cxx_string(a.path) .. ","
    end
    cue_rows[#cue_rows + 1] = string.format("\t{ %s, EOmCueKind::%s, 0x%04x, %d, %d, %s },", cxx_string(id),
      enum_name(M.KINDS[kind]), mask, begin, #assets, cue.placeholder and "true" or "false")
    begin = begin + #assets
  end
  if begin == 0 then out[#out + 1] = "\tnullptr," end
  out[#out + 1] = "};"
  out[#out + 1] = ""
  out[#out + 1] = "static const FOmCueCatalogRow GOmCueRows[] = {"
  for _, row in ipairs(cue_rows) do out[#out + 1] = row end
  out[#out + 1] = "};"
  out[#out + 1] = ""
  -- original path -> cues, in the catalog's own order (the first is the primary cue)
  local path_rows, cue_refs = {}, {}
  for _, p in ipairs(paths) do
    local a = catalog.assets[p]
    local kind = assert(M.ASSET_KINDS[a.kind], "asset " .. p .. " kind " .. tostring(a.kind))
    local first = #cue_refs
    for _, id in ipairs(a.cues or {}) do cue_refs[#cue_refs + 1] = assert(cue_index[id], "asset " .. p .. " cue " .. id) end
    path_rows[#path_rows + 1] = string.format("\t{ %s, EOmCueAssetKind::%s, %d, %d },", cxx_string(p), kind, first, #cue_refs - first)
  end
  out[#out + 1] = "static const int32 GOmCuePathCueIndices[] = {"
  for i = 1, #cue_refs, 16 do
    local line = {}
    for j = i, math.min(i + 15, #cue_refs) do line[#line + 1] = tostring(cue_refs[j]) end
    out[#out + 1] = "\t" .. table.concat(line, ", ") .. ","
  end
  if #cue_refs == 0 then out[#out + 1] = "\t-1," end
  out[#out + 1] = "};"
  out[#out + 1] = ""
  out[#out + 1] = "static const FOmCuePathRow GOmCuePathRows[] = {"
  for _, row in ipairs(path_rows) do out[#out + 1] = row end
  out[#out + 1] = "};"
  return table.concat(out, "\r\n") .. "\r\n"
end

local function read(path)
  local f = io.open(path, "rb")
  if not f then return nil end
  local s = f:read("a")
  f:close()
  return s
end

function M.main(args)
  local root, out, check = b.root, nil, false
  local i = 1
  while i <= #args do
    local a = args[i]
    if a == "--root" then root = args[i + 1]; i = i + 1
    elseif a == "--out" then out = args[i + 1]; i = i + 1
    elseif a == "--check" then check = true
    else error("unknown argument " .. a) end
    i = i + 1
  end
  out = out or (root .. "/" .. M.OUT)
  local text = M.render(dofile(root .. "/" .. M.CATALOG))
  if check then
    if read(out) ~= text then
      io.stderr:write(out .. " is stale; run tools\\lua\\lua.exe scripts\\gen_ue_cue_table.lua\n")
      return 1
    end
    print("cue table up to date: " .. out)
    return 0
  end
  local f = assert(io.open(out, "wb"))
  f:write(text)
  f:close()
  print("wrote " .. out)
  return 0
end

if not CUE_TABLE_AS_MODULE then os.exit(M.main(arg)) end
return M
