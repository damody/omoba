-- Build-time catalog of the native bridge's static dispatch cases.
local source=debug.getinfo(1,'S').source:sub(2)
package.path=assert(source:match('^(.*)[/\\]'))..'/?.lua;'..package.path
local b=require('_bootstrap')
local path,lfs=b.lib('path'),require('lfs')
local private=path.join(b.root,'omfue/Plugins/BpGeneratorUltimate/Source/UECPMCPBridge/Private')
local dispatch=path.join(private,'Dispatch')
local names={}
for file in lfs.dir(dispatch) do
  if file:match('%.cpp$') then
    local text=path.read(path.join(dispatch,file))
    -- Only statically named dispatch cases. Dynamically registered extensions
    -- continue to use the existing dispatcher rather than invented tool names.
    for _,variable in ipairs{'CT','CommandType'} do
      for name in text:gmatch(variable..'%s*==%s*TEXT%(%s*"([%w_]+)"%s*%)') do
        names[name]=true
      end
    end
  end
end
local ordered={}
for name in pairs(names) do ordered[#ordered+1]=name end
table.sort(ordered)
assert(#ordered>0,'native MCP dispatch catalog is empty')
local lines={'// Generated by scripts/generate_ue_mcp_catalog.lua; intentionally no include guard.'}
for _,name in ipairs(ordered) do lines[#lines+1]='UECP_MCP_STATIC_TOOL("'..name..'")' end
local text=table.concat(lines,'\n')..'\n'
local output=path.join(private,'MCPStaticTools.inl')
if not path.is_file(output) or path.read(output)~=text then path.write(output,text,true) end
print('Native MCP static dispatch catalog: '..#ordered..' tools')
