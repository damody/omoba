-- The compact source roster the content build validates hero `source_ref` against: repository,
-- pinned commit and every source hero id with its Traditional Chinese name and its unit stats
-- (the X_2.txt unit KV, values as written). Derived from the provenance catalog
-- (source-catalog.lua) so the build never loads the 7 MB catalog itself.
local M = {}

M.NAME = "history_nobu"

-- Unit KV key -> roster stat name, in output order. starting_mana is optional (some units omit it).
M.STATS = {
  { "AttributePrimary", "primary" },
  { "AttributeBaseStrength", "base_strength" }, { "AttributeBaseAgility", "base_agility" },
  { "AttributeBaseIntelligence", "base_intelligence" },
  { "AttributeStrengthGain", "strength_gain" }, { "AttributeAgilityGain", "agility_gain" },
  { "AttributeIntelligenceGain", "intelligence_gain" },
  { "StatusHealth", "health" }, { "StatusHealthRegen", "health_regen" },
  { "StatusMana", "mana" }, { "StatusManaRegen", "mana_regen" }, { "StatusStartingMana", "starting_mana" },
  { "ArmorPhysical", "armor" }, { "MagicalResistance", "magic_resistance" },
  { "AttackDamageMin", "attack_damage_min" }, { "AttackDamageMax", "attack_damage_max" },
  { "AttackRate", "attack_rate" }, { "AttackRange", "attack_range" },
  { "MovementSpeed", "movement_speed" }, { "MovementTurnRate", "turn_rate" },
  { "AttackAcquisitionRange", "acquisition_range" },
}
M.OPTIONAL = { starting_mana = true }
local PRIMARY = { DOTA_ATTRIBUTE_STRENGTH = "strength", DOTA_ATTRIBUTE_AGILITY = "agility",
  DOTA_ATTRIBUTE_INTELLECT = "intelligence", DOTA_ATTRIBUTE_ALL = "universal" }

-- Stats of one unit, from its KV fields (text only). A field the unit omits inherits the hero
-- base unit's (`defaults`, npc_heroes_override.txt npc_dota_hero_base), as Dota does. Unknown
-- primaries and non-numbers are left out, so the content build sees them as missing rather
-- than as invented values.
function M.stats(unit, defaults)
  local fields = {}
  for _, field in ipairs(defaults or {}) do if field.key then fields[field.key] = field.value end end
  for _, field in ipairs((unit or {}).fields or {}) do fields[field.key] = field.value end
  local stats = {}
  for _, pair in ipairs(M.STATS) do
    local value = fields[pair[1]]
    if value ~= nil then
      value = tostring(value):match("^%s*(.-)%s*$")
      if pair[2] == "primary" then stats.primary = PRIMARY[value]
      else stats[pair[2]] = tonumber(value) end
    end
  end
  return stats
end

function M.rows(catalog)
  local rows = {}
  for _, hero in ipairs(catalog.heroes) do
    rows[#rows + 1] = { id = hero.source_hero_id, name = hero.name_zhtw or "", listed_on_site = hero.listed_on_site == true,
      stats = M.stats(hero.unit, catalog.hero_unit_defaults) }
  end
  table.sort(rows, function(a, b) return a.id < b.id end)
  return rows
end

-- Shortest text that reads back as the same number (2.2, not 2.2000000000000002).
local function number(value)
  if value == math.floor(value) and math.abs(value) < 1e15 then return string.format("%d", value) end
  for digits = 1, 17 do
    local text = string.format("%." .. digits .. "g", value)
    if tonumber(text) == value then return text end
  end
  return string.format("%.17g", value)
end

local function render_stats(stats)
  local parts = {}
  for _, pair in ipairs(M.STATS) do
    local value = stats[pair[2]]
    if value ~= nil then
      parts[#parts + 1] = pair[2] .. " = " .. (type(value) == "string" and string.format("%q", value) or number(value))
    end
  end
  return "{ " .. table.concat(parts, ", ") .. " }"
end

local function quote(text) return string.format("%q", text) end

function M.render(catalog)
  local out = {
    "-- Generated by scripts/hero_source_index.lua roster from source-catalog.lua; do not edit.\n",
    "-- Every playable hero names one of these heroes in its source_ref:\n",
    "--   source_ref = '" .. M.NAME .. "@<commit>:<id>'\n",
    "return function(ctx)\n  return {\n",
    "    name = " .. quote(M.NAME) .. ",\n",
    "    repository = " .. quote(catalog.source.repository) .. ",\n",
    "    commit = " .. quote(catalog.source.commit) .. ",\n",
    "    heroes = {\n",
  }
  for _, row in ipairs(M.rows(catalog)) do
    out[#out + 1] = string.format("      { id = %s, name = %s, listed_on_site = %s,\n        stats = %s },\n",
      quote(row.id), quote(row.name), tostring(row.listed_on_site), render_stats(row.stats))
  end
  out[#out + 1] = "    },\n  }\nend\n"
  return table.concat(out)
end

-- The source_ref a hero package's provenance declares.
function M.source_ref(provenance)
  local name = provenance.repository and provenance.repository:match("/([^/]+)$")
  assert(name == M.NAME, "provenance repository is not " .. M.NAME .. ": " .. tostring(provenance.repository))
  assert(type(provenance.commit) == "string" and provenance.commit:match("^%x+$") and #provenance.commit == 40,
    "provenance commit must be a 40-hex sha")
  assert(type(provenance.source_hero_id) == "string" and provenance.source_hero_id:match("^[ABC]%d%d$"),
    "provenance source_hero_id must look like B01")
  return M.NAME .. "@" .. provenance.commit .. ":" .. provenance.source_hero_id
end

return M
